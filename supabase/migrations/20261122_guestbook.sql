create table if not exists public.guestbook_entries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 24),
  message text not null check (char_length(message) between 1 and 240),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

create index if not exists guestbook_entries_approved_created_at_idx
  on public.guestbook_entries (created_at desc)
  where status = 'approved';

alter table public.guestbook_entries enable row level security;
revoke all on table public.guestbook_entries from public, anon, authenticated;
grant select, insert, update, delete on table public.guestbook_entries to service_role;
grant usage, select on sequence public.guestbook_entries_id_seq to service_role;

create table if not exists public.guestbook_rate_limits (
  ip_hash text primary key check (char_length(ip_hash) = 64),
  window_started_at timestamptz not null default now(),
  request_count integer not null default 1 check (request_count > 0)
);

alter table public.guestbook_rate_limits enable row level security;
revoke all on table public.guestbook_rate_limits from public, anon, authenticated;
grant select, insert, update, delete on table public.guestbook_rate_limits to service_role;

create index if not exists guestbook_rate_limits_window_started_at_idx
  on public.guestbook_rate_limits (window_started_at);

create or replace function public.consume_guestbook_rate_limit(p_ip_hash text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
declare
  current_count integer;
begin
  if p_ip_hash is null or char_length(p_ip_hash) <> 64 then
    return false;
  end if;

  delete from public.guestbook_rate_limits
  where window_started_at < now() - interval '24 hours';

  insert into public.guestbook_rate_limits (ip_hash, window_started_at, request_count)
  values (p_ip_hash, now(), 1)
  on conflict (ip_hash) do update
  set
    window_started_at = case
      when public.guestbook_rate_limits.window_started_at <= now() - interval '1 hour'
        then now()
      else public.guestbook_rate_limits.window_started_at
    end,
    request_count = case
      when public.guestbook_rate_limits.window_started_at <= now() - interval '1 hour'
        then 1
      else public.guestbook_rate_limits.request_count + 1
    end
  returning request_count into current_count;

  return current_count <= 3;
end;
$function$;

revoke all on function public.consume_guestbook_rate_limit(text) from public, anon, authenticated;
grant execute on function public.consume_guestbook_rate_limit(text) to service_role;
